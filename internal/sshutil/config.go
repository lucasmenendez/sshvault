package sshutil

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"sshvault/internal/vault"
)

const (
	ConfigBeginMarker = "# >>> sshvault managed block >>>"
	ConfigEndMarker   = "# <<< sshvault managed block <<<"
	hostIDPrefix      = "# sshvault:host="
)

var ErrConfigMarkers = fmt.Errorf("malformed sshvault managed block")

// RenderHost returns the config lines for one host, without the ID comment.
func RenderHost(h *vault.Host, keysByID map[string]*vault.Key, display func(string) string) string {
	var b strings.Builder
	b.WriteString("Host ")
	b.WriteString(strings.Join(h.Patterns, " "))
	b.WriteString("\n")
	if h.HostName != "" {
		fmt.Fprintf(&b, "    HostName %s\n", h.HostName)
	}
	if h.User != "" {
		fmt.Fprintf(&b, "    User %s\n", h.User)
	}
	if h.Port > 0 && h.Port != 22 {
		fmt.Fprintf(&b, "    Port %d\n", h.Port)
	}
	for _, id := range h.IdentityKeyIDs {
		if k := keysByID[id]; k != nil {
			fmt.Fprintf(&b, "    IdentityFile %s\n", display(k.Filename))
		}
	}
	for _, o := range h.Options {
		if o.Value == "" {
			fmt.Fprintf(&b, "    %s\n", o.Name)
		} else {
			fmt.Fprintf(&b, "    %s %s\n", o.Name, o.Value)
		}
	}
	return strings.TrimRight(b.String(), "\n")
}

func hostSegment(h *vault.Host, keysByID map[string]*vault.Key, display func(string) string) string {
	return hostIDPrefix + h.ID + "\n" + RenderHost(h, keysByID, display)
}

// RenderBlock builds the full managed block, or "" when no hosts are deployed.
func RenderBlock(hosts []*vault.Host, keys []*vault.Key, deployed map[string]bool, display func(string) string) string {
	keysByID := map[string]*vault.Key{}
	for _, k := range keys {
		keysByID[k.ID] = k
	}
	var segs []string
	for _, h := range hosts {
		if deployed[h.ID] {
			segs = append(segs, hostSegment(h, keysByID, display))
		}
	}
	if len(segs) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(ConfigBeginMarker)
	b.WriteString("\n# This block is generated by sshvault. Do not edit it by hand.\n")
	for _, s := range segs {
		b.WriteString("\n")
		b.WriteString(s)
		b.WriteString("\n")
	}
	b.WriteString(ConfigEndMarker)
	return b.String()
}

type parsedConfig struct {
	Before string
	Block  string
	After  string
	Found  bool
}

func parseConfig(content string) (parsedConfig, error) {
	beginCount := strings.Count(content, ConfigBeginMarker)
	endCount := strings.Count(content, ConfigEndMarker)
	if beginCount > 1 || endCount > 1 {
		return parsedConfig{}, fmt.Errorf("%w: multiple markers", ErrConfigMarkers)
	}
	if beginCount != endCount {
		return parsedConfig{}, fmt.Errorf("%w: incomplete markers", ErrConfigMarkers)
	}
	if beginCount == 0 {
		return parsedConfig{Before: content}, nil
	}

	start := strings.Index(content, ConfigBeginMarker)
	if start > 0 && content[start-1] != '\n' {
		return parsedConfig{}, fmt.Errorf("%w: begin marker is not on its own line", ErrConfigMarkers)
	}
	endIdx := strings.Index(content[start:], ConfigEndMarker)
	if endIdx < 0 {
		return parsedConfig{}, fmt.Errorf("%w: missing end marker", ErrConfigMarkers)
	}
	endIdx += start
	if endIdx > 0 && content[endIdx-1] != '\n' {
		return parsedConfig{}, fmt.Errorf("%w: end marker is not on its own line", ErrConfigMarkers)
	}
	lineEnd := endIdx + len(ConfigEndMarker)
	if lineEnd < len(content) && content[lineEnd] == '\r' {
		lineEnd++
	}
	if lineEnd < len(content) && content[lineEnd] == '\n' {
		lineEnd++
	}
	return parsedConfig{
		Before: content[:start],
		Block:  content[start:lineEnd],
		After:  content[lineEnd:],
		Found:  true,
	}, nil
}

func stripBlock(content string) (string, bool, error) {
	p, err := parseConfig(content)
	if err != nil {
		return "", false, err
	}
	if !p.Found {
		return content, false, nil
	}
	rest := strings.TrimLeft(p.Before+p.After, "\n")
	return rest, true, nil
}

func withBlock(content, block string) string {
	if block == "" {
		return content
	}
	content = strings.TrimLeft(content, "\n")
	if content == "" {
		return block + "\n"
	}
	return block + "\n\n" + content
}

// DeployedHostIDs extracts IDs from the managed block.
func DeployedHostIDs(content string) (map[string]bool, error) {
	p, err := parseConfig(content)
	if err != nil {
		return nil, err
	}
	out := map[string]bool{}
	if !p.Found {
		return out, nil
	}
	for _, line := range strings.Split(p.Block, "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, hostIDPrefix) {
			id := strings.TrimSpace(strings.TrimPrefix(line, hostIDPrefix))
			if id != "" {
				out[id] = true
			}
		}
	}
	return out, nil
}

func hostSegments(block string) map[string]string {
	out := map[string]string{}
	lines := strings.Split(block, "\n")
	currentID := ""
	var current []string
	flush := func() {
		if currentID != "" {
			out[currentID] = strings.TrimRight(strings.Join(current, "\n"), "\n")
		}
	}
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, hostIDPrefix) {
			flush()
			currentID = strings.TrimSpace(strings.TrimPrefix(trimmed, hostIDPrefix))
			current = []string{trimmed}
			continue
		}
		if trimmed == ConfigEndMarker {
			flush()
			currentID = ""
			current = nil
			continue
		}
		if currentID != "" {
			current = append(current, line)
		}
	}
	flush()
	return out
}

func normalizeBlock(s string) string {
	s = strings.ReplaceAll(s, "\r\n", "\n")
	lines := strings.Split(s, "\n")
	for i := range lines {
		lines[i] = strings.TrimRight(lines[i], " \t")
	}
	for len(lines) > 0 && strings.TrimSpace(lines[0]) == "" {
		lines = lines[1:]
	}
	for len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "" {
		lines = lines[:len(lines)-1]
	}
	return strings.Join(lines, "\n")
}

func (m *Manager) readConfig() (string, error) {
	b, err := os.ReadFile(m.configTarget())
	if err != nil {
		if os.IsNotExist(err) {
			return "", nil
		}
		return "", err
	}
	return string(b), nil
}

func (m *Manager) configTarget() string {
	p := m.ConfigPath()
	if resolved, err := filepath.EvalSymlinks(p); err == nil {
		return resolved
	}
	if info, err := os.Lstat(p); err == nil && info.Mode()&os.ModeSymlink != 0 {
		if target, err := os.Readlink(p); err == nil {
			if !filepath.IsAbs(target) {
				target = filepath.Join(filepath.Dir(p), target)
			}
			if resolved, err := filepath.EvalSymlinks(target); err == nil {
				return resolved
			}
			return target
		}
	}
	return p
}

// ConfigSnapshot returns the raw config text and the currently deployed host IDs.
func (m *Manager) ConfigSnapshot() (string, map[string]bool, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	return m.configSnapshotLocked()
}

func (m *Manager) configSnapshotLocked() (string, map[string]bool, error) {
	content, err := m.readConfig()
	if err != nil {
		return "", nil, err
	}
	ids, err := DeployedHostIDs(content)
	return content, ids, err
}

// WriteManaged regenerates the managed block and places it at the top of config.
func (m *Manager) WriteManaged(hosts []*vault.Host, keys []*vault.Key, deployed map[string]bool) (string, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	return m.writeManagedLocked(hosts, keys, deployed)
}

func (m *Manager) writeManagedLocked(hosts []*vault.Host, keys []*vault.Key, deployed map[string]bool) (string, error) {
	if err := m.EnsureDir(); err != nil {
		return "", err
	}
	content, err := m.readConfig()
	if err != nil {
		return "", err
	}
	block := RenderBlock(hosts, keys, deployed, m.DisplayPath)
	rest, _, err := stripBlock(content)
	if err != nil {
		return "", err
	}
	next := withBlock(rest, block)
	if next == content {
		return next, nil
	}
	target := m.configTarget()
	if info, err := os.Stat(target); err == nil {
		if err := m.backupFile(target); err != nil {
			return "", err
		}
		mode := info.Mode().Perm()
		if mode == 0 {
			mode = 0o600
		}
		if err := writeAtomic(target, []byte(next), mode); err != nil {
			return "", err
		}
	} else if os.IsNotExist(err) {
		if block == "" {
			return "", nil
		}
		if err := writeAtomic(target, []byte(next), 0o600); err != nil {
			return "", err
		}
	} else {
		return "", err
	}
	return next, nil
}

// DeployHost adds one host to the managed block.
func (m *Manager) DeployHost(hosts []*vault.Host, keys []*vault.Key, id string) (map[string]bool, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	_, deployed, err := m.configSnapshotLocked()
	if err != nil {
		return nil, err
	}
	deployed[id] = true
	if _, err := m.writeManagedLocked(hosts, keys, deployed); err != nil {
		return nil, err
	}
	return deployed, nil
}

// UndeployHost removes one host from the managed block.
func (m *Manager) UndeployHost(hosts []*vault.Host, keys []*vault.Key, id string) (map[string]bool, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	_, deployed, err := m.configSnapshotLocked()
	if err != nil {
		return nil, err
	}
	delete(deployed, id)
	if _, err := m.writeManagedLocked(hosts, keys, deployed); err != nil {
		return nil, err
	}
	return deployed, nil
}

// HostStatuses returns the deployment state of every host.
func (m *Manager) HostStatuses(hosts []*vault.Host, keys []*vault.Key) (map[string]Status, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	content, err := m.readConfig()
	if err != nil {
		return nil, err
	}
	block := ""
	if p, err := parseConfig(content); err != nil {
		return nil, err
	} else if p.Found {
		block = p.Block
	}
	keysByID := map[string]*vault.Key{}
	for _, k := range keys {
		keysByID[k.ID] = k
	}
	segs := hostSegments(block)
	out := map[string]Status{}
	for _, h := range hosts {
		actual, ok := segs[h.ID]
		if !ok {
			out[h.ID] = Status{State: StateNotDeployed}
			continue
		}
		expected := hostIDPrefix + h.ID + "\n" + RenderHost(h, keysByID, m.DisplayPath)
		if normalizeBlock(actual) == normalizeBlock(expected) {
			out[h.ID] = Status{State: StateDeployed}
		} else {
			out[h.ID] = Status{State: StateDrift, Message: "managed block differs from the vault"}
		}
	}
	return out, nil
}

// OutsideHostPatterns returns Host patterns that live outside the managed block.
func OutsideHostPatterns(content string) ([]string, error) {
	p, err := parseConfig(content)
	if err != nil {
		return nil, err
	}
	rest := p.Before + p.After
	var out []string
	for _, line := range strings.Split(rest, "\n") {
		t := strings.TrimSpace(line)
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		fields := strings.Fields(t)
		if len(fields) >= 2 && strings.EqualFold(fields[0], "Host") {
			out = append(out, fields[1:]...)
		}
	}
	return out, nil
}

// ConfigWarnings reports patterns that are also defined outside the managed
// block. Because our block sits at the top, our values take precedence.
func (m *Manager) ConfigWarnings(hosts []*vault.Host) ([]string, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	content, err := m.readConfig()
	if err != nil {
		return nil, err
	}
	outside, err := OutsideHostPatterns(content)
	if err != nil {
		return nil, err
	}
	set := map[string]bool{}
	for _, p := range outside {
		set[strings.ToLower(p)] = true
	}
	var warnings []string
	for _, h := range hosts {
		for _, p := range h.Patterns {
			if set[strings.ToLower(p)] {
				warnings = append(warnings, "host pattern "+p+" is also defined outside the managed block; the managed block takes precedence")
			}
		}
	}
	return warnings, nil
}

// ConfigPreview returns the full config that would result from the deployed set.
func (m *Manager) ConfigPreview(hosts []*vault.Host, keys []*vault.Key, deployed map[string]bool) (string, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	content, err := m.readConfig()
	if err != nil {
		return "", err
	}
	block := RenderBlock(hosts, keys, deployed, m.DisplayPath)
	rest, _, err := stripBlock(content)
	if err != nil {
		return "", err
	}
	return withBlock(rest, block), nil
}

func (m *Manager) ManagedBlock() (string, error) {
	m.configMu.Lock()
	defer m.configMu.Unlock()
	content, err := m.readConfig()
	if err != nil {
		return "", err
	}
	p, err := parseConfig(content)
	if err != nil {
		return "", err
	}
	return p.Block, nil
}
